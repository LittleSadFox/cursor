// Regenerates src/db/migrations.ts from src/db/migrations/*.sql so core stays driver- and fs-free.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '../src/db/migrations');
const files = readdirSync(dir)
  .filter((name) => name.endsWith('.sql'))
  .sort();

const entries = files.map((name) => {
  const id = name.replace(/\.sql$/, '').replace('-', '_');
  const sql = readFileSync(join(dir, name), 'utf8');
  return `  {\n    id: '${id}',\n    sql: ${JSON.stringify(sql)},\n  },`;
});

const out = `/** SQL migrations applied by \`applyMigrations\`. Generated by \`pnpm --filter @climbing-coach/core migrations:embed\`. */

export type Migration = { id: string; sql: string };

export const MIGRATIONS: readonly Migration[] = [
${entries.join('\n')}
];
`;

writeFileSync(join(dir, '../migrations.ts'), out);
console.log(`embedded ${files.length} migration(s)`);
